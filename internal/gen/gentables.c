// Prints the exp and log tables of ARM Optimized Routines as Go source.
//
// The tables are compiled from the upstream data files with the configuration
// glibc uses on x86-64 without FMA (HAVE_FAST_FMA=0, 128-entry tables).
//
// build and run (from the repository root):
//   cc -DHAVE_FAST_FMA=0 -Ireferences/arm-optimized-routines/math \
//      fasttext/internal/gen/gentables.c \
//      references/arm-optimized-routines/math/exp_data.c \
//      references/arm-optimized-routines/math/log_data.c \
//      references/arm-optimized-routines/math/exp2f_data.c -o /tmp/gentables
//   /tmp/gentables > fasttext/libm_tables.go
#include <inttypes.h>
#include <stdio.h>
#include <string.h>

#include "math_config.h"

static uint64_t bits(double x) {
  uint64_t u;
  memcpy(&u, &x, 8);
  return u;
}

static void scalar(const char* name, double x) {
  printf("\t%s = 0x%016" PRIx64 " // %a\n", name, bits(x), x);
}

static void doubles(const char* name, const double* p, int n) {
  printf("var %s = [%d]uint64{\n", name, n);
  for (int i = 0; i < n; i++) {
    printf("\t0x%016" PRIx64 ", // %a\n", bits(p[i]), p[i]);
  }
  printf("}\n\n");
}

static void words(const char* name, const uint64_t* p, int n) {
  printf("var %s = [%d]uint64{", name, n);
  for (int i = 0; i < n; i++) {
    printf("%s0x%016" PRIx64 ",", i % 4 ? " " : "\n\t", p[i]);
  }
  printf("\n}\n\n");
}

int main(void) {
  printf("// Code generated by internal/gen/gentables.c; DO NOT EDIT.\n\n");
  printf("// Tables from ARM Optimized Routines (math/exp_data.c, math/log_data.c,\n");
  printf("// math/exp2f_data.c), Copyright (c) 2017-2026 Arm Limited, used under the\n");
  printf("// MIT license. See LICENSE-arm-optimized-routines.\n\n");
  printf("package fasttext\n\n");
  printf("// IEEE-754 bit patterns of the scalar constants.\n");
  printf("const (\n");
  scalar("exp2fInvLn2ScaledBits", __exp2f_data.invln2_scaled);
  scalar("exp2fShiftBits", __exp2f_data.shift);
  scalar("expInvLn2NBits", __exp_data.invln2N);
  scalar("expNegLn2HiNBits", __exp_data.negln2hiN);
  scalar("expNegLn2LoNBits", __exp_data.negln2loN);
  scalar("expShiftBits", __exp_data.shift);
  scalar("logLn2HiBits", __log_data.ln2hi);
  scalar("logLn2LoBits", __log_data.ln2lo);
  printf(")\n\n");
  words("exp2fTab", __exp2f_data.tab, 1 << EXP2F_TABLE_BITS);
  doubles("exp2fPolyScaledBits", __exp2f_data.poly_scaled, EXP2F_POLY_ORDER);
  doubles("expPolyBits", __exp_data.poly, 4);
  words("expTab", __exp_data.tab, 2 * (1 << EXP_TABLE_BITS));
  doubles("logPolyBits", __log_data.poly, LOG_POLY_ORDER - 1);
  doubles("logPoly1Bits", __log_data.poly1, LOG_POLY1_ORDER - 1);
  printf("// logTab holds invc and logc per subinterval.\n");
  words("logTab", (const uint64_t*)__log_data.tab, 2 * (1 << LOG_TABLE_BITS));
  printf("// logTab2 holds chi and clo per subinterval.\n");
  words("logTab2", (const uint64_t*)__log_data.tab2, 2 * (1 << LOG_TABLE_BITS));
  return 0;
}
